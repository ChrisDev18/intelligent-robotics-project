#!/usr/bin/env python3
"""Make worlds/home_tasks.sdf: the home world stripped down for task practice.

Keeps only the walls (rooms and doorways), the coloured floors and the Beta
pick-and-place cube. Removes all furniture, plants, task-marker patches and
the walking humans, so nothing gets in the way while the cleaning and
pick-and-place tasks are being developed.

    python3 tools/make_task_world.py

Reads worlds/home_no_humans.sdf, so re-run this after regenerating the main worlds.
"""
import re
from pathlib import Path

KEEP_PREFIXES = ('ground_plane', 'wall_', 'floor_')
KEEP_NAMES = {'beta_pick_item'}

worlds = Path(__file__).resolve().parent.parent / 'worlds'
src = (worlds / 'home_no_humans.sdf').read_text()

# Each <model name='...'> ... </model> block is self-contained (no nested models).
pattern = re.compile(r"\n?[ \t]*<model name=['\"]([^'\"]+)['\"]>.*?</model>", re.S)
kept, removed = [], []


def filter_model(match):
    name = match.group(1)
    if name in KEEP_NAMES or name.startswith(KEEP_PREFIXES):
        kept.append(name)
        return match.group(0)
    removed.append(name)
    return ''


out = pattern.sub(filter_model, src)
out = out.replace('Generated by tools/generate_world.py',
                  'Generated by tools/make_task_world.py from home_no_humans.sdf')
(worlds / 'home_tasks.sdf').write_text(out)
print(f'Wrote {worlds / "home_tasks.sdf"}')
print(f'Kept {len(kept)}: {", ".join(kept)}')
print(f'Removed {len(removed)} models')
